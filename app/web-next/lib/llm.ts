// Multi-provider LLM abstraction (ADR-0074 Phase 1) — a single
// `complete()` entry point over OpenAI-compatible, Anthropic, and Gemini
// adapters. Provider/credentials come from env:
//   CO_NEWBIZ_LLM_PROVIDER : openai | anthropic | gemini | custom (default: none)
//   CO_NEWBIZ_LLM_BASE_URL : provider base URL (openai/custom)
//   CO_NEWBIZ_LLM_API_KEY  : API key
//   CO_NEWBIZ_LLM_MODEL    : model id
// With no provider configured, complete() returns null and callers fall back
// to deterministic synthesis — the platform must stay fully functional
// without an LLM (Agentic-first does not mean LLM-dependent).
// Every response is tagged with its source so execution records can always
// answer "was this generated by a model or synthesized from data?".

