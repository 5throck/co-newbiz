export interface SynthesisResult {
  text: string;
  source: "synthesis";
  provider: "deterministic";
  model: "template";
  /** Why the model path was not used (e.g. validation_failed); absent for plain "no provider". */
  reason?: string;
}

export type LlmOutcome = LlmResult | SynthesisResult;

export interface LlmMessage {
  role: "system" | "user";
  content: string;
}

interface ProviderConfig {
  provider: string;
  baseUrl?: string;
  apiKey?: string;
  model?: string;
}

// Repo-root .env loading lives in ./root-env.ts (shared by every route).
export { loadRootEnvPipelineKeys };

export function getProviderConfig(): ProviderConfig | null {
  loadRootEnvPipelineKeys();
  const provider = process.env.CO_NEWBIZ_LLM_PROVIDER?.trim();
  if (!provider || provider === "none") return null;
  const cfg: ProviderConfig = {
    provider,
    baseUrl: process.env.CO_NEWBIZ_LLM_BASE_URL?.replace(/\/$/, ""),
    apiKey: process.env.CO_NEWBIZ_LLM_API_KEY,
    model: process.env.CO_NEWBIZ_LLM_MODEL,
  };
  if (!cfg.apiKey || !cfg.model) return null;
  return cfg;
}

export function isLlmConfigured(): boolean {
  return getProviderConfig() !== null;
}

// ── capabilities (design §5.2 #7) ───────────────────────────────────────────
// Declared by config, never inferred from the model name: a custom base URL
// may support only a subset. CO_NEWBIZ_LLM_CAPS=structured,cache,stream
export interface LlmCaps {
  structured: boolean;
  cache: boolean;
  stream: boolean;
}

export function getLlmCaps(): LlmCaps {
  loadRootEnvPipelineKeys();
  const set = new Set(
    (process.env.CO_NEWBIZ_LLM_CAPS ?? "")
      .split(",")
      .map((s) => s.trim().toLowerCase())
      .filter(Boolean),
  );
  return { structured: set.has("structured"), cache: set.has("cache"), stream: set.has("stream") };
}

interface CallSpec {
  messages: LlmMessage[];
  /** Sampling temperature — carried on anthropic/gemini bodies; silently ignored on openai-compatible/custom (omitted, user decision 2026-11-13). */
  temperature?: number;
  maxTokens?: number;
  /** Provider-native structured output (only set when the structured cap is on). */
  structured?: { name: string; jsonSchema: Record<string, unknown> };
  cacheSystem?: boolean;
  stream?: boolean;
  /** Per-call abort deadline shared across retry attempts; absent keeps the existing 60 s transport timeout. */
  signal?: AbortSignal;
}

interface ProviderReply {
  text: string;
  /** Anthropic forced-tool input, already an object. */
  toolInput?: unknown;
  /** Provider finish/stop reason (e.g. "length" / "max_tokens" = truncated output). */
  finishReason?: string;
  usage: LlmUsage | null;
}

const addUsage = (a: LlmUsage | null, b: LlmUsage | null): LlmUsage | null => {
  if (!a) return b;
  if (!b) return a;
  return {
    ...a,
    inputTokens: a.inputTokens + b.inputTokens,
    outputTokens: a.outputTokens + b.outputTokens,
    cacheReadTokens: a.cacheReadTokens + b.cacheReadTokens,
    cacheWriteTokens: a.cacheWriteTokens + b.cacheWriteTokens,
  };
};

// ── token-cap parameter resolution (design 2026-11-13-llm-max-completion-tokens) ──
// OpenAI reasoning models reject `max_tokens` and demand `max_completion_tokens`,
// while most third-party OpenAI-compatible servers only honor the older name.
// The parameter NAME is resolved per request: explicit env knob → exact-host
// heuristic → compatibility default, with an in-band 400-signature probe as the
// last resort, memoized per provider|baseUrl|model for the process lifetime.
// Sibling decision (same design, §8.3, user decision 2026-11-13): `temperature`
// is never sent on the openai-compatible/custom branch — reasoning models
// reject non-default sampling values, and omission is universally accepted.

export type TokenCapParam = "max_tokens" | "max_completion_tokens";

// 6000 = the previous empty-response retry ceiling (1500 x 4): a first-attempt
// default aligned with today's last-resort ceiling, sized for reasoning models
// whose reasoning tokens count against the cap (user decision, 2026-11-13,
// amending DEC-20261113-02 point 5). Anthropic/Gemini branches are untouched.
const DEFAULT_MAX_TOKENS_BY_PROVIDER: Record<string, number> = {
  anthropic: 1500,
  gemini: 1500,
  openai: 6000,
  "openai-compatible": 6000,
  custom: 6000,
};

/** Provider-aware default output budget (user decision 2026-11-13): openai-compatible/custom 6000, anthropic/gemini 1500. */
export function defaultMaxTokens(provider: string): number {
  return DEFAULT_MAX_TOKENS_BY_PROVIDER[provider] ?? 6000;
}

const tokenParamMemo = new Map<string, TokenCapParam>();
// \x27 (apostrophe) is escaped so the i18n-lint's string-state scanner (which has no
// regex-literal state) never sees a bare quote inside this regex literal.
const TOKEN_PARAM_REJECTION_SIGNATURE = /max_tokens[\x27 ]+is not supported with this model/i;
let knobWarned = false;

const memoKey = (cfg: ProviderConfig): string =>
  `${cfg.provider}|${cfg.baseUrl ?? "(default)"}|${cfg.model ?? "(default)"}`;

const hostOf = (baseUrl?: string): string | undefined => {
  if (!baseUrl) return undefined;
  try {
    return new URL(baseUrl).host;
  } catch {
    return undefined;
  }
};

/**
 * Resolve the output-cap parameter name for one request (design §3.1):
 * 1. explicit knob CO_NEWBIZ_LLM_MAX_TOKENS_PARAM (max_tokens | max_completion_tokens | auto)
 * 2. auto + baseUrl host == api.openai.com → max_completion_tokens (exact host match, never a substring)
 * 3. auto + any other host → memoized probe result, else max_tokens
 */
export function resolveTokenCapParam(cfg: ProviderConfig): TokenCapParam {
  const knob = process.env.CO_NEWBIZ_LLM_MAX_TOKENS_PARAM?.trim().toLowerCase();
  if (knob === "max_tokens" || knob === "max_completion_tokens") return knob;
  if (knob && knob !== "auto" && !knobWarned) {
    knobWarned = true;
    console.warn(
      `llm.ts: unrecognized CO_NEWBIZ_LLM_MAX_TOKENS_PARAM value '${knob}' (valid: max_tokens, max_completion_tokens, auto) — behaving as auto.`,
    );
  }
  if (hostOf(cfg.baseUrl) === "api.openai.com") return "max_completion_tokens";
  return tokenParamMemo.get(memoKey(cfg)) ?? "max_tokens";
}

/**
 * In-band probe (design §3.2): when the provider itself states the unsupported-parameter
 * error, flip the memo so the next buildRequest sends max_completion_tokens at the same budget.
 */
function noteParamRejection(cfg: ProviderConfig, status: number, bodyText: string): boolean {
  if (status !== 400 || !TOKEN_PARAM_REJECTION_SIGNATURE.test(bodyText)) return false;
  tokenParamMemo.set(memoKey(cfg), "max_completion_tokens");
  return true;
}

/** Test-only: clear memoized token-parameter decisions and the one-shot knob warning between tests. */
export function __resetTokenParamStateForTests(): void {
  tokenParamMemo.clear();
  knobWarned = false;
}

/** Empty content after the provider consumed the budget — the only failure class the x4 retry serves. */
class EmptyResponseError extends Error {}

/** Transport with the existing single retry (4x token budget bound to empty responses only — design §3.3). */
async function runProvider(cfg: ProviderConfig, spec: CallSpec): Promise<ProviderReply> {
  const url = resolveUrl(cfg);
  const baseBudget = spec.maxTokens ?? defaultMaxTokens(cfg.provider);
  let lastError: unknown = null;
  // undefined keeps the spec as-is (original budget); set only after an empty response.
  let retryBudget: number | undefined;
  let usage: LlmUsage | null = null;
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      const attemptSpec = retryBudget === undefined ? spec : { ...spec, maxTokens: retryBudget };
      const res = await fetch(url, {
        method: "POST",
        headers: buildHeaders(cfg),
        body: JSON.stringify(buildRequest(cfg, attemptSpec)),
        signal: spec.signal ?? AbortSignal.timeout(60_000),
      });
      if (!res.ok) {
        const bodyText = await res.text();
        if (noteParamRejection(cfg, res.status, bodyText)) {
          throw new Error(
            `LLM HTTP 400: endpoint rejected 'max_tokens'; retrying with 'max_completion_tokens'. ${bodyText.slice(0, 200)}`,
          );
        }
        throw new Error(`LLM HTTP ${res.status}: ${bodyText.slice(0, 200)}`);
      }
      const json = (await res.json()) as Record<string, unknown>;
      usage = addUsage(usage, parseUsage(cfg.provider, cfg.model ?? "unknown", json));
      const text = extractText(cfg.provider, json);
      const toolInput = extractToolInput(json);
      if (!text.trim() && toolInput === undefined) {
        throw new EmptyResponseError(
          "LLM returned an empty response (reasoning tokens may have exhausted the output-token cap).",
        );
      }
      return { text, toolInput, usage, finishReason: extractFinishReason(json) };
    } catch (err) {
      lastError = err;
      // The x4 exists to give reasoning models a bigger ceiling after they burned
      // the first one on reasoning with no text — a parameter-format 400 is a
      // request-construction error and resends at the original budget instead.
      retryBudget = err instanceof EmptyResponseError ? baseBudget * 4 : undefined;
    }
  }
  throw lastError instanceof Error ? lastError : new Error("LLM call failed.");
}

export interface CompleteDetailed {
  text: string;
  usage: LlmUsage;
  /** Provider finish/stop reason when reported; "length" / "max_tokens" means the output was cut off. */
  finishReason?: string;
}

/** Like complete() but also returns usage (provider-reported, or flagged estimate). */
export async function completeDetailed(
  messages: LlmMessage[],
  opts: {
    temperature?: number;
    maxTokens?: number;
    agent: AgentCallMeta;
    dryRun?: DryRunContext;
    signal?: AbortSignal;
  },
): Promise<CompleteDetailed> {
  requireAgentMeta(opts.agent);
  const cfg = getProviderConfig();
  if (!cfg) throw new Error("LLM provider is not configured.");
  const started = Date.now();
  const model = cfg.model ?? "unknown";
  try {
    const reply = await runProvider(cfg, {
      messages,
      temperature: opts.temperature,
      maxTokens: opts.maxTokens,
      signal: opts.signal,
    });
    const usage =
      reply.usage ?? estimatedUsage(cfg.provider, model, messages.map((m) => m.content).join("\n"), reply.text);
    // 직접 호출 지점도 ADR-0128 런 장부에 남는다 — completeOrFallback 경로의 기록과 중복되지 않도록
    // 성공/실패 로그는 이곳(complete)에서만 담당한다.
    logAgentCall(
      opts.agent,
      { source: "llm", provider: cfg.provider, model },
      true,
      null,
      Date.now() - started,
      usage,
      opts.dryRun,
    );
    return { text: reply.text, usage, finishReason: reply.finishReason };
  } catch (err) {
    const reason = err instanceof Error ? err.message : String(err);
    logAgentCall(
      opts.agent,
      { source: "llm", provider: cfg.provider, model },
      false,
      reason,
      Date.now() - started,
      null,
      opts.dryRun,
    );
    throw err instanceof Error ? err : new Error("LLM call failed.");
  }
}

/** One shot: messages → text. Throws on provider errors after a single retry. */
export async function complete(
  messages: LlmMessage[],
  opts: {
    temperature?: number;
    maxTokens?: number;
    agent: AgentCallMeta;
    dryRun?: DryRunContext;
    signal?: AbortSignal;
  },
): Promise<string> {
  return (await completeDetailed(messages, opts)).text;
}

// ── structured output (design §5.2 #1-3) ────────────────────────────────────

export interface StructuredOptions<T> {
  messages: LlmMessage[];
  schema: z.ZodType<T>;
  schemaName: string;
  cache?: { system?: boolean };
  agent: AgentCallMeta;
  temperature?: number;
  maxTokens?: number;
  signal?: AbortSignal;
}

export interface StructuredResult<T> {
  value: T;
  usage: LlmUsage;
  source: "llm";
}

function toJsonSchema(schema: z.ZodType): Record<string, unknown> {
  const js = z.toJSONSchema(schema) as Record<string, unknown>;
  delete js.$schema;
  return js;
}

/** Pull the JSON value out of a reply: forced-tool input, else the outermost JSON object/array in text. */
function extractJsonValue(reply: ProviderReply): unknown {
  if (reply.toolInput !== undefined) return reply.toolInput;
  const text = reply.text.replace(/```(?:json)?/g, "");
  const o = text.indexOf("{");
  const a = text.indexOf("[");
  const start = o >= 0 && (a < 0 || o < a) ? o : a;
  if (start < 0) return undefined;
  const end = text.lastIndexOf(text[start] === "{" ? "}" : "]");
  if (end <= start) return undefined;
  try {
    return JSON.parse(text.slice(start, end + 1));
  } catch {
    return undefined;
  }
}

function describeIssues(err: z.ZodError | null): string {
  if (!err) return "reply was not parseable JSON";
  return err.issues
    .slice(0, 12)
    .map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`)
    .join("; ");
}

/**
 * Structured completion: provider-native JSON schema (when the structured cap
 * is declared) or instruct-and-parse, ALWAYS followed by Zod validation, one
 * repair retry that names only the failing paths, then an explicit fallback
 * (source "synthesis", reason "validation_failed" | "llm_error" | "not_configured").
 */
export async function completeStructured<T>(
  opts: StructuredOptions<T>,
): Promise<StructuredResult<T> | SynthesisResult> {
  requireAgentMeta(opts.agent);
  const cfg = getProviderConfig();
  if (!cfg) {
    logAgentCall(opts.agent, SYNTH, true, null, 0, null);
    return { ...synthesis(), reason: "not_configured" };
  }
  const caps = getLlmCaps();
  const model = cfg.model ?? "unknown";
  const started = Date.now();
  const jsonSchema = toJsonSchema(opts.schema);
  const native = caps.structured ? { name: opts.schemaName, jsonSchema } : undefined;
  const messages = opts.messages;
  const withInstruction: LlmMessage[] = native
    ? messages
    : [
        ...messages,
        {
          role: "user",
          content: `Respond with ONE JSON value and nothing else. It must conform to this JSON Schema (${opts.schemaName}):\n${JSON.stringify(jsonSchema)}`,
        },
      ];
  const base = {
    temperature: opts.temperature ?? 0,
    maxTokens: opts.maxTokens ?? defaultMaxTokens(cfg.provider),
    structured: native,
    cacheSystem: caps.cache && opts.cache?.system === true,
  };
  const promptText = withInstruction.map((m) => m.content).join("\n");
  let usage: LlmUsage | null = null;
  const finish = (ok: boolean, error: string | null, value?: T): StructuredResult<T> | SynthesisResult => {
    const finalUsage = usage ?? estimatedUsage(cfg.provider, model, promptText, "");
    logAgentCall(
      opts.agent,
      ok ? { source: "llm", provider: cfg.provider, model } : SYNTH,
      ok,
      error,
      Date.now() - started,
      usage ? finalUsage : null,
    );
    if (ok && value !== undefined) return { value, usage: finalUsage, source: "llm" };
    return { ...synthesis(), reason: error ?? "llm_error" };
  };
  try {
    let last: z.ZodError | null = null;
    let current = withInstruction;
    for (let round = 0; round < 2; round++) {
      if (opts.signal?.aborted) throw new Error("aborted");
      const reply = await runProvider(cfg, { ...base, messages: current });
      usage = addUsage(usage, reply.usage);
      const raw = extractJsonValue(reply);
      const parsed = raw === undefined ? null : opts.schema.safeParse(raw);
      if (parsed?.success) {
        if (!usage) usage = estimatedUsage(cfg.provider, model, promptText, reply.text);
        return finish(true, null, parsed.data);
      }
      last = parsed ? parsed.error : null;
      // Repair follow-up: failing paths only — never echo the raw model output.
      current = [
        ...withInstruction,
        {
          role: "user",
          content: `Your previous reply failed validation (${describeIssues(last)}). Reply again with ONLY the corrected JSON value for ${opts.schemaName}.`,
        },
      ];
    }
    return finish(false, "validation_failed");
  } catch (err) {
    return finish(false, err instanceof Error ? err.message : "llm_error");
  }
}

// ── streaming (design §5.2 #4) ──────────────────────────────────────────────

export type LlmStreamEvent = { type: "text"; delta: string } | { type: "usage"; usage: LlmUsage };

function mergeMaxUsage(a: LlmUsage | null, b: LlmUsage): LlmUsage {
  if (!a) return b;
  return {
    ...a,
    inputTokens: Math.max(a.inputTokens, b.inputTokens),
    outputTokens: Math.max(a.outputTokens, b.outputTokens),
    cacheReadTokens: Math.max(a.cacheReadTokens, b.cacheReadTokens),
    cacheWriteTokens: Math.max(a.cacheWriteTokens, b.cacheWriteTokens),
  };
}

/** Extract (text delta, usage) pieces from one parsed SSE data object. */
function parseStreamChunk(
  provider: string,
  model: string,
  json: Record<string, unknown>,
): { delta: string; usage: LlmUsage | null } {
  if (provider === "gemini") {
    return { delta: extractText("gemini", json), usage: parseUsage("gemini", model, json) };
  }
  if (provider === "anthropic") {
    const d = json.delta as { type?: string; text?: string } | undefined;
    const delta = json.type === "content_block_delta" && d?.type === "text_delta" ? (d.text ?? "") : "";
    // message_start carries input usage (nested), message_delta carries output usage.
    const msg = json.message as Record<string, unknown> | undefined;
    const usage = parseUsage("anthropic", model, msg ?? json);
    return { delta, usage };
  }
  const choices = json.choices as Array<{ delta?: { content?: string } }> | undefined;
  return { delta: choices?.[0]?.delta?.content ?? "", usage: parseUsage(provider, model, json) };
}

/**
 * Text deltas then a final usage event. When the stream cap is not declared
 * the call is made non-streamed and delivered as one text event, so callers
 * never branch on provider support.
 */
export async function* stream(opts: {
  messages: LlmMessage[];
  temperature?: number;
  maxTokens?: number;
  agent: AgentCallMeta;
  signal?: AbortSignal;
}): AsyncGenerator<LlmStreamEvent, void, void> {
  requireAgentMeta(opts.agent);
  const cfg = getProviderConfig();
  if (!cfg) throw new Error("LLM provider is not configured.");
  const model = cfg.model ?? "unknown";
  if (!getLlmCaps().stream) {
    const r = await completeDetailed(opts.messages, opts);
    yield { type: "text", delta: r.text };
    yield { type: "usage", usage: r.usage };
    return;
  }
  const started = Date.now();
  let text = "";
  let usage: LlmUsage | null = null;
  try {
    const res = await fetch(resolveUrl(cfg, true), {
      method: "POST",
      headers: buildHeaders(cfg),
      body: JSON.stringify(
        buildRequest(cfg, {
          messages: opts.messages,
          temperature: opts.temperature,
          maxTokens: opts.maxTokens,
          stream: true,
        }),
      ),
      signal: opts.signal ?? AbortSignal.timeout(120_000),
    });
    if (!res.ok || !res.body) {
      const bodyText = await res.text().catch(() => "");
      // No mid-generator resend here (design §3.2): the memo write is the whole
      // job — the caller-level retry loop re-enters with the corrected body.
      if (noteParamRejection(cfg, res.status, bodyText)) {
        throw new Error(
          `LLM HTTP 400: endpoint rejected 'max_tokens'; retrying with 'max_completion_tokens'. ${bodyText.slice(0, 200)}`,
        );
      }
      throw new Error(`LLM HTTP ${res.status}: ${bodyText.slice(0, 200)}`);
    }
    const reader = res.body.getReader();
    const decoder = new TextDecoder();
    let buf = "";
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      buf += decoder.decode(value, { stream: true });
      for (;;) {
        const nl = buf.indexOf("\n");
        if (nl < 0) break;
        const line = buf.slice(0, nl).trim();
        buf = buf.slice(nl + 1);
        if (!line.startsWith("data:")) continue;
        const data = line.slice(5).trim();
        if (!data || data === "[DONE]") continue;
        let json: Record<string, unknown>;
        try {
          json = JSON.parse(data) as Record<string, unknown>;
        } catch {
          continue;
        }
        const piece = parseStreamChunk(cfg.provider, model, json);
        if (piece.delta) {
          text += piece.delta;
          yield { type: "text", delta: piece.delta };
        }
        // Anthropic splits usage over message_start/message_delta; others repeat totals — keep the max per field.
        if (piece.usage) usage = mergeMaxUsage(usage, piece.usage);
      }
    }
    const finalUsage =
      usage ?? estimatedUsage(cfg.provider, model, opts.messages.map((m) => m.content).join("\n"), text);
    logAgentCall(
      opts.agent,
      { source: "llm", provider: cfg.provider, model },
      true,
      null,
      Date.now() - started,
      finalUsage,
    );
    yield { type: "usage", usage: finalUsage };
  } catch (err) {
    logAgentCall(
      opts.agent,
      { source: "llm", provider: cfg.provider, model },
      false,
      err instanceof Error ? err.message : String(err),
      Date.now() - started,
      null,
    );
    throw err instanceof Error ? err : new Error("LLM stream failed.");
  }
}

// ── request / response shapes ───────────────────────────────────────────────

function buildRequest(cfg: ProviderConfig, spec: CallSpec) {
  const { messages, structured } = spec;
  const temperature = spec.temperature ?? 0.3;
  const maxTokens = spec.maxTokens ?? defaultMaxTokens(cfg.provider);
  const system = messages
    .filter((m) => m.role === "system")
    .map((m) => m.content)
    .join("\n");
  const turns = messages.filter((m) => m.role !== "system");
  if (cfg.provider === "anthropic") {
    return {
      model: cfg.model,
      // Reasoning models (GLM) otherwise spend the token budget on thinking
      // blocks before emitting any text — disable when the provider accepts it.
      thinking: { type: "disabled" },
      max_tokens: maxTokens,
      temperature,
      // cache_control on the stable system prompt only when the cache cap is declared.
      system: system
        ? spec.cacheSystem
          ? [{ type: "text", text: system, cache_control: { type: "ephemeral" } }]
          : system
        : undefined,
      messages: turns.map((m) => ({ role: m.role, content: m.content })),
      ...(structured
        ? {
            tools: [
              {
                name: structured.name,
                description: `Return the ${structured.name} result.`,
                input_schema: structured.jsonSchema,
              },
            ],
            tool_choice: { type: "tool", name: structured.name },
          }
        : {}),
      ...(spec.stream ? { stream: true } : {}),
    };
  }
  if (cfg.provider === "gemini") {
    return {
      systemInstruction: system ? { parts: [{ text: system }] } : undefined,
      contents: turns.map((m) => ({ role: "user", parts: [{ text: m.content }] })),
      generationConfig: {
        temperature,
        maxOutputTokens: maxTokens,
        ...(structured ? { responseMimeType: "application/json", responseJsonSchema: structured.jsonSchema } : {}),
      },
    };
  }
  // openai-compatible / custom — the output-cap parameter NAME is resolved per
  // request (knob → api.openai.com heuristic → memoized probe default, see
  // resolveTokenCapParam above); the budget itself is unchanged by the resolver.
  // `temperature` is OMITTED entirely (user decision, 2026-11-13): OpenAI
  // reasoning models reject any non-default sampling value ("'temperature'
  // does not support 0.3 with this model. Only the default (1) value is
  // supported."), and omission is universally accepted by third-party
  // OpenAI-compatible servers because the parameter is optional in the
  // Chat Completions contract — strictly safer than a probe or sending the
  // default explicitly. Accepted cost: no per-call sampling tuning on this
  // branch; a spec.temperature set by callers is silently ignored here (the
  // anthropic and gemini branches below still carry it).
  const tokenCapParam = resolveTokenCapParam(cfg);
  return {
    model: cfg.model,
    [tokenCapParam]: maxTokens,
    messages,
    ...(structured
      ? {
          response_format: {
            type: "json_schema",
            json_schema: { name: structured.name, schema: structured.jsonSchema, strict: true },
          },
        }
      : {}),
    ...(spec.stream ? { stream: true, stream_options: { include_usage: true } } : {}),
  };
}

function buildHeaders(cfg: ProviderConfig): Record<string, string> {
  if (cfg.provider === "anthropic") {
    return {
      "content-type": "application/json",
      "x-api-key": cfg.apiKey ?? "",
      "anthropic-version": "2023-06-01",
    };
  }
  if (cfg.provider === "gemini") {
    return {
      "content-type": "application/json",
      "x-goog-api-key": cfg.apiKey ?? "",
    };
  }
  return { "content-type": "application/json", authorization: `Bearer ${cfg.apiKey ?? ""}` };
}

function resolveUrl(cfg: ProviderConfig, streaming = false): string {
  if (cfg.provider === "anthropic") {
    const base = cfg.baseUrl?.replace(/\/$/, "");
    if (!base) return "https://api.anthropic.com/v1/messages";
    // Operators give the bare Anthropic-compatible base (e.g. a proxy root);
    // the messages path still has to be appended.
    return base.endsWith("/messages") ? base : `${base}/v1/messages`;
  }
  if (cfg.provider === "gemini")
    // Key travels in the x-goog-api-key HEADER (see buildHeaders), never the
    // URL — query-string keys leak into proxy/access logs.
    return `${cfg.baseUrl ?? "https://generativelanguage.googleapis.com/v1beta"}/models/${cfg.model}:${streaming ? "streamGenerateContent?alt=sse" : "generateContent"}`;
  return `${cfg.baseUrl ?? "https://api.openai.com/v1"}/chat/completions`;
}

function extractText(provider: string, json: Record<string, unknown>): string {
  if (provider === "gemini") {
    const candidates = json.candidates as Array<{ content?: { parts?: Array<{ text?: string }> } }> | undefined;
    return candidates?.[0]?.content?.parts?.map((p) => p.text ?? "").join("") ?? "";
  }
  const choices = json.choices as Array<{ message?: { content?: string } }> | undefined;
  if (choices?.[0]?.message?.content) return choices[0].message.content;
  const content = json.content as Array<{ text?: string }> | undefined;
  if (Array.isArray(content)) return content.map((c) => c.text ?? "").join("");
  return "";
}

function extractFinishReason(json: Record<string, unknown>): string | undefined {
  const choices = json.choices as Array<{ finish_reason?: string }> | undefined;
  if (typeof choices?.[0]?.finish_reason === "string") return choices[0].finish_reason;
  if (typeof json.stop_reason === "string") return json.stop_reason;
  const candidates = json.candidates as Array<{ finishReason?: string }> | undefined;
  return typeof candidates?.[0]?.finishReason === "string" ? candidates[0].finishReason : undefined;
}

function extractToolInput(json: Record<string, unknown>): unknown {
  const content = json.content as Array<{ type?: string; input?: unknown }> | undefined;
  if (!Array.isArray(content)) return undefined;
  return content.find((c) => c.type === "tool_use")?.input;
}

const SYNTH = { source: "synthesis", provider: "deterministic", model: "template" } as const;
const synthesis = (): SynthesisResult => ({ text: "", ...SYNTH });

/** Result envelope for orchestrator features: LLM text when configured, deterministic synthesis otherwise. */
export type LlmOrFallback = { source: LlmSource; provider: string; text: string };

/** ADR-0128 — 에이전트 런 장부 기록용 메타데이터. agent_key는 agents/ 로스터의
 * 역할명(예: risk-officer, pm)을 따르고, purpose는 무엇을 만들었는지 한 줄이다.
 * ADR-0155 — projectId(딜), functionName, promptHash는 딜별 토큰·비용 집계용. */
export interface AgentCallMeta {
  key: string;
  purpose: string;
  contextType?: string;
  contextId?: string;
  projectId?: string;
  functionName?: string;
  promptHash?: string;
}

/** ADR-0183 D2 — 분류 근거 어휘. "catalog"은 단계 산출물 provenance용(후속 로우에서
 * 표면화), pm-router 자체는 "rules" | "llm"만 생산한다. */
export type ClassifiedBy = "catalog" | "llm" | "rules";

/**
 * 2026-09-15-runtime-pm-agent-orchestration §6.6 (D5) — 드라이런 오버라이드
 * 컨텍스트. 존재하면 (a) system 메시지가 promptOverride로 대체되고,
 * (b) agent.key가 agentOverride로 교체된다(로스터 검증은 requireAgentMeta가
 * 그대로 수행 — 관문은 오버라이드에도 적용된다), (c) 런 장부 기록에
 * is_dry_run=1 + dry_run_group_id가 남는다. dryRun이 없는 호출의 동작은
 * 이 필드 도입 이전과 동일하다(운영 경로 무변경).
 * 이 컨텍스트는 세션 스코프 저장소(dry_run_session, 0172)의 값만 전달한다 —
 * SSOT(prompts.json 등)을 쓰는 경로는 여기에 없다.
 */
export interface DryRunContext {
  /** dry_run_session.id — llm_call_log.dry_run_group_id 조인 키. */
  groupId: string;
  /** 카탈로그 시스템 프롬프트 대체문(없으면 원본 사용). */
  promptOverride?: string;
  /** 카탈로그 에이전트 키 대체(없으면 원본 사용). 반드시 agents/ 로스터 키. */
  agentOverride?: string;
}

/** PM 관문 위반 — 선언 없는 LLM 호출 또는 로스터에 없는 에이전트 키 (ADR-0183 D2). */
export class PmGateError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "PmGateError";
  }
}

/**
 * 모든 LLM 진입점의 필수 선언 관문 (ADR-0183 D2, design §6.3). provider·네트워크·
 * LLM 구성 확인보다 먼저 실행된다 — 선언 강제는 LLM 구성과 무관한 컴파일/런타임
 * 불변식이고("LLM 없이도 완전 기능" 유지), 폴백·합성 경로도 선언을 요구한다.
 * 관문에 걸린 호출은 런 장부에도 남지 않는다 — 미기록이 아니라 불가능이 정답이다.
 */
function requireAgentMeta(agent: AgentCallMeta | undefined): AgentCallMeta {
  if (!agent || typeof agent.key !== "string" || agent.key.trim() === "") {
    throw new PmGateError(
      "PM gateway: agent call meta is required — pass agent: { key, purpose } (an agents/ roster key, e.g. via prompts.promptAgent()) to every LLM entry point (ADR-0183 D2).",
    );
  }
  if (!AGENT_KEYS.has(agent.key)) {
    throw new PmGateError(
      `PM gateway: agent key '${agent.key}' is not in the agents/ roster (ADR-0128). Declare a rostered agent key or add the agent to agents/*.md.`,
    );
  }
  return agent;
}

function logAgentCall(
  agent: AgentCallMeta,
  outcome: { source: "llm" | "synthesis"; provider: string; model: string },
  ok: boolean,
  error: string | null,
  latencyMs: number,
  usage: LlmUsage | null = null,
  dryRun?: DryRunContext,
): void {
  const projectId = agent.projectId ?? (agent.contextType === "project" ? agent.contextId : undefined);
  if (outcome.source === "llm") {
    const end = Date.now();
    // emitGenAiSpan은 고정 속성 세트만 받는다 — 드라이런 태깅용 커스텀 속성이
    // 없어 §6.6의 스팬 태깅은 스킵한다(런 장부 플래그가 근거의 SSOT다).
    emitGenAiSpan(
      {
        system: outcome.provider,
        requestModel: outcome.model,
        responseModel: usage?.model,
        inputTokens: usage ? usage.inputTokens + usage.cacheReadTokens + usage.cacheWriteTokens : undefined,
        outputTokens: usage?.outputTokens,
        projectId,
        functionName: agent.functionName ?? agent.key,
      },
      end - latencyMs,
      end,
      ok,
    );
  }
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports -- node built-ins only
    const { getDb } = require("../../../db/client.ts") as typeof import("../../../db/client.ts");
    // eslint-disable-next-line @typescript-eslint/no-require-imports -- node built-ins only
    const { ulid } = require("../../../db/lib/ulid.ts") as typeof import("../../../db/lib/ulid.ts");
    getDb().run(
      `INSERT INTO llm_call_log (id, agent_key, purpose, context_type, context_id, source, provider, model, ok, error, latency_ms, created_by, created_at,
                                 input_tokens, output_tokens, cache_read_tokens, cache_write_tokens, cost_usd, usage_estimated, project_id, function_name, prompt_hash,
                                 is_dry_run, dry_run_group_id)
       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
      [
        ulid(),
        agent.key,
        agent.purpose,
        agent.contextType ?? null,
        agent.contextId ?? null,
        outcome.source,
        outcome.provider,
        outcome.model,
        ok ? 1 : 0,
        error,
        latencyMs,
        "system",
        new Date().toISOString(),
        usage ? usage.inputTokens : null,
        usage ? usage.outputTokens : null,
        usage ? usage.cacheReadTokens : null,
        usage ? usage.cacheWriteTokens : null,
        usage ? costUsd(usage) : null,
        usage?.estimated ? 1 : 0,
        projectId ?? null,
        agent.functionName ?? null,
        agent.promptHash ?? null,
        dryRun?.groupId ? 1 : 0,
        dryRun?.groupId ?? null,
      ],
    );
  } catch (err) {
    // 런 장부 기록 실패는 본 기능을 막지 않는다 — 관찰 가능성 손실만 남긴다.
    console.error("llm_call_log write failed:", err instanceof Error ? err.message : err);
  }
}

export async function completeOrFallback(
  messages: LlmMessage[],
  fallback: () => string,
  opts: { temperature?: number; maxTokens?: number; agent: AgentCallMeta; dryRun?: DryRunContext },
): Promise<LlmOrFallback> {
  requireAgentMeta(opts.agent);
  // §6.6 D5 — 오버라이드는 세션 스코프 값(dry_run_session)의 전달일 뿐이며,
  // SSOT을 읽거나 쓰지 않는다. agentOverride 교체 후에도 requireAgentMeta가
  // 로스터 등록을 강제하므로 PM 관문은 오버라이드 경로에서도 유효하다.
  const dry = opts.dryRun;
  const agent: AgentCallMeta = dry?.agentOverride ? { ...opts.agent, key: dry.agentOverride } : opts.agent;
  // agentOverride 교체분도 즉시 검증한다 — 관문 위반은 LLM 구성 여부와 무관하게
  // 폴백이 아니라 예외여야 한다(미기록이 아니라 불가능이 정답).
  requireAgentMeta(agent);
  const effectiveMessages: LlmMessage[] = dry?.promptOverride
    ? messages.map((m) => (m.role === "system" ? { ...m, content: dry.promptOverride as string } : m))
    : messages;
  const cfg = getProviderConfig();
  if (!cfg) {
    logAgentCall(agent, SYNTH, true, null, 0, null, dry);
    return { source: "synthesis", provider: "deterministic", text: fallback() };
  }
  const started = Date.now();
  try {
    // llm 경로의 런 장부 기록은 complete() 내부에서 이루어진다.
    const text = await complete(effectiveMessages, {
      temperature: opts.temperature,
      maxTokens: opts.maxTokens,
      agent,
      dryRun: dry,
    });
    return { source: "llm", provider: cfg.provider, text };
  } catch (err) {
    // 관문 위반은 폴백으로 흡수되지 않는다 — 결정론 폴백은 호출 실패의 대응이지
    // 선언 위반의 대응이 아니다 (design §6.3, ADR-0183 D2).
    if (err instanceof PmGateError) throw err;
    // 폴백 자체는 설계된 동작이지만 사유가 로그에 없으면 현장에서 진단 불가 —
    // 실제 원인(HTTP 상태·타임아웃·빈 응답)을 남긴다.
    const reason = err instanceof Error ? err.message : String(err);
    console.error(`llm fallback (${cfg.provider}/${cfg.model}):`, reason);
    logAgentCall(agent, SYNTH, false, reason, Date.now() - started, null, dry);
    return { source: "synthesis", provider: "deterministic", text: fallback() };
  }
}
