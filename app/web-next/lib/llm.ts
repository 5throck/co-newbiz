// Multi-provider LLM abstraction (ADR-0074 Phase 1) — a single
// `complete()` entry point over OpenAI-compatible, Anthropic, and Gemini
// adapters. Provider/credentials come from env:
//   CO_NEWBIZ_LLM_PROVIDER : openai | anthropic | gemini | custom (default: none)
//   CO_NEWBIZ_LLM_BASE_URL : provider base URL (openai/custom)
//   CO_NEWBIZ_LLM_API_KEY  : API key
//   CO_NEWBIZ_LLM_MODEL    : model id
// With no provider configured, complete() returns null and callers fall back
// to deterministic synthesis — the platform must stay fully functional
// without an LLM (Agentic-first does not mean LLM-dependent).
// Every response is tagged with its source so execution records can always
// answer "was this generated by a model or synthesized from data?".

export type LlmSource = "llm" | "synthesis";

export interface LlmResult {
  text: string;
  source: "llm";
  provider: string;
  model: string;
}

export interface SynthesisResult {
  text: string;
  source: "synthesis";
  provider: "deterministic";
  model: "template";
}

export type LlmOutcome = LlmResult | SynthesisResult;

export interface LlmMessage {
  role: "system" | "user";
  content: string;
}

interface ProviderConfig {
  provider: string;
  baseUrl?: string;
  apiKey?: string;
  model?: string;
}

// The Next.js server runs with cwd app/web-next, so Next only auto-loads
// .env files from there — but operators configure CO_NEWBIZ_LLM_*, DART_API_KEY,
// TAVILY_API_KEY etc. in the repo-root .env. Walk up from cwd and import
// pipeline keys that are not already in the environment (never overriding
// explicitly-set values).
const PIPELINE_ENV_KEYS = /^(CO_NEWBIZ_LLM_[A-Z_]+|DART_API_KEY|ECOS_API_KEY|KRX_API_KEY|TAVILY_API_KEY)$/;
let rootEnvLoaded = false;
export function loadRootEnvPipelineKeys(): void {
  if (rootEnvLoaded) return;
  rootEnvLoaded = true;
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports -- node built-ins only
    const { existsSync, readFileSync } = require("node:fs") as typeof import("node:fs");
    // eslint-disable-next-line @typescript-eslint/no-require-imports -- node built-ins only
    const { dirname, join } = require("node:path") as typeof import("node:path");
    // cwd is the anchor (next start runs from app/web-next); import.meta.dir
    // is unreliable inside the bundled server chunks.
    let dir = /*turbopackIgnore: true*/ process.cwd();
    for (let i = 0; i < 5; i++) {
      const envPath = join(dir, ".env");
      if (existsSync(envPath)) {
        for (const line of readFileSync(envPath, "utf-8").split(/\r?\n/)) {
          const m = line.match(/^([A-Z_]+)=(.*)$/);
          if (m && PIPELINE_ENV_KEYS.test(m[1]) && process.env[m[1]] === undefined) {
            process.env[m[1]] = m[2].trim();
          }
        }
        if (process.env.CO_NEWBIZ_LLM_PROVIDER && process.env.DART_API_KEY && process.env.TAVILY_API_KEY) return;
      }
      const parent = dirname(dir);
      if (parent === dir) return;
      dir = parent;
    }
  } catch {
    // env discovery is best-effort — the deterministic fallback still works
  }
}

export function getProviderConfig(): ProviderConfig | null {
  loadRootEnvPipelineKeys();
  const provider = process.env.CO_NEWBIZ_LLM_PROVIDER?.trim();
  if (!provider || provider === "none") return null;
  const cfg: ProviderConfig = {
    provider,
    baseUrl: process.env.CO_NEWBIZ_LLM_BASE_URL?.replace(/\/$/, ""),
    apiKey: process.env.CO_NEWBIZ_LLM_API_KEY,
    model: process.env.CO_NEWBIZ_LLM_MODEL,
  };
  if (!cfg.apiKey || !cfg.model) return null;
  return cfg;
}

export function isLlmConfigured(): boolean {
  return getProviderConfig() !== null;
}

/** One shot: messages → text. Throws on provider errors after a single retry. */
export async function complete(
  messages: LlmMessage[],
  opts: { temperature?: number; maxTokens?: number } = {},
): Promise<string> {
  const cfg = getProviderConfig();
  if (!cfg) throw new Error("LLM provider is not configured.");
  const url = resolveUrl(cfg);
  let lastError: unknown = null;
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      // Reasoning models can spend the whole token budget on thinking and
      // return an empty text part — retry once with a 4× token budget.
      const attemptOpts = attempt === 0 ? opts : { ...opts, maxTokens: (opts.maxTokens ?? 1500) * 4 };
      const body = buildRequest(cfg, messages, attemptOpts);
      const res = await fetch(url, {
        method: "POST",
        headers: buildHeaders(cfg),
        body: JSON.stringify(body),
        signal: AbortSignal.timeout(60_000),
      });
      if (!res.ok) throw new Error(`LLM HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`);
      const json = (await res.json()) as Record<string, unknown>;
      const text = extractText(cfg.provider, json);
      if (!text.trim()) throw new Error("LLM returned an empty response (reasoning tokens may have exhausted max_tokens).");
      return text;
    } catch (err) {
      lastError = err;
      if (attempt === 0) continue;
      break;
    }
  }
  throw lastError instanceof Error ? lastError : new Error("LLM call failed.");
}

function buildRequest(cfg: ProviderConfig, messages: LlmMessage[], opts: { temperature?: number; maxTokens?: number }) {
  const temperature = opts.temperature ?? 0.3;
  const maxTokens = opts.maxTokens ?? 1500;
  if (cfg.provider === "anthropic") {
    const system = messages.filter((m) => m.role === "system").map((m) => m.content).join("\n");
    return {
      model: cfg.model,
      // Reasoning models (GLM) otherwise spend the token budget on thinking
      // blocks before emitting any text — disable when the provider accepts it.
      thinking: { type: "disabled" },
      max_tokens: maxTokens,
      temperature,
      system: system || undefined,
      messages: messages.filter((m) => m.role !== "system").map((m) => ({ role: m.role, content: m.content })),
    };
  }
  // openai-compatible / custom
  return {
    model: cfg.model,
    temperature,
    max_tokens: maxTokens,
    messages,
  };
}

function buildHeaders(cfg: ProviderConfig): Record<string, string> {
  if (cfg.provider === "anthropic") {
    return {
      "content-type": "application/json",
      "x-api-key": cfg.apiKey ?? "",
      "anthropic-version": "2023-06-01",
    };
  }
  if (cfg.provider === "gemini") {
    return {
      "content-type": "application/json",
      "x-goog-api-key": cfg.apiKey ?? "",
    };
  }
  return { "content-type": "application/json", authorization: `Bearer ${cfg.apiKey ?? ""}` };
}

function resolveUrl(cfg: ProviderConfig): string {
  if (cfg.provider === "anthropic") {
    const base = cfg.baseUrl?.replace(/\/$/, "");
    if (!base) return "https://api.anthropic.com/v1/messages";
    // Operators give the bare Anthropic-compatible base (e.g. a proxy root);
    // the messages path still has to be appended.
    return base.endsWith("/messages") ? base : `${base}/v1/messages`;
  }
  if (cfg.provider === "gemini")
    // Key travels in the x-goog-api-key HEADER (see buildHeaders), never the
    // URL — query-string keys leak into proxy/access logs.
    return `${cfg.baseUrl ?? "https://generativelanguage.googleapis.com/v1beta"}/models/${cfg.model}:generateContent`;
  return `${cfg.baseUrl ?? "https://api.openai.com/v1"}/chat/completions`;
}

function extractText(provider: string, json: Record<string, unknown>): string {
  if (provider === "gemini") {
    const candidates = json.candidates as Array<{ content?: { parts?: Array<{ text?: string }> } }> | undefined;
    return candidates?.[0]?.content?.parts?.map((p) => p.text ?? "").join("") ?? "";
  }
  const choices = json.choices as Array<{ message?: { content?: string } }> | undefined;
  if (choices?.[0]?.message?.content) return choices[0].message.content;
  const content = json.content as Array<{ text?: string }> | undefined;
  if (Array.isArray(content)) return content.map((c) => c.text ?? "").join("");
  return "";
}

/** Result envelope for orchestrator features: LLM text when configured, deterministic synthesis otherwise. */
export type LlmOrFallback = { source: LlmSource; provider: string; text: string };

/** ADR-0128 — 에이전트 런 장부 기록용 메타데이터. agent_key는 agents/ 로스터의
 * 역할명(예: risk-officer, pm)을 따르고, purpose는 무엇을 만들었는지 한 줄이다. */
export interface AgentCallMeta {
  key: string;
  purpose: string;
  contextType?: string;
  contextId?: string;
}

function logAgentCall(
  agent: AgentCallMeta | undefined,
  outcome: { source: "llm" | "synthesis"; provider: string; model: string },
  ok: boolean,
  error: string | null,
  latencyMs: number,
): void {
  if (!agent) return;
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports -- node built-ins only
    const { getDb } = require("../../../db/client.ts") as typeof import("../../../db/client.ts");
    // eslint-disable-next-line @typescript-eslint/no-require-imports -- node built-ins only
    const { ulid } = require("../../../db/lib/ulid.ts") as typeof import("../../../db/lib/ulid.ts");
    getDb().run(
      `INSERT INTO llm_call_log (id, agent_key, purpose, context_type, context_id, source, provider, model, ok, error, latency_ms, created_by, created_at)
       VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)`,
      [ulid(), agent.key, agent.purpose, agent.contextType ?? null, agent.contextId ?? null,
        outcome.source, outcome.provider, outcome.model, ok ? 1 : 0, error, latencyMs, "system", new Date().toISOString()],
    );
  } catch (err) {
    // 런 장부 기록 실패는 본 기능을 막지 않는다 — 관찰 가능성 손실만 남긴다.
    console.error("llm_call_log write failed:", err instanceof Error ? err.message : err);
  }
}

export async function completeOrFallback(
  messages: LlmMessage[],
  fallback: () => string,
  opts: { temperature?: number; maxTokens?: number; agent?: AgentCallMeta } = {},
): Promise<LlmOrFallback> {
  const cfg = getProviderConfig();
  if (!cfg) {
    logAgentCall(opts.agent, { source: "synthesis", provider: "deterministic", model: "template" }, true, null, 0);
    return { source: "synthesis", provider: "deterministic", text: fallback() };
  }
  const started = Date.now();
  try {
    const text = await complete(messages, opts);
    logAgentCall(opts.agent, { source: "llm", provider: cfg.provider, model: cfg.model ?? "unknown" }, true, null, Date.now() - started);
    return { source: "llm", provider: cfg.provider, text };
  } catch (err) {
    // 폴백 자체는 설계된 동작이지만 사유가 로그에 없으면 현장에서 진단 불가 —
    // 실제 원인(HTTP 상태·타임아웃·빈 응답)을 남긴다.
    const reason = err instanceof Error ? err.message : String(err);
    console.error(`llm fallback (${cfg.provider}/${cfg.model}):`, reason);
    logAgentCall(opts.agent, { source: "synthesis", provider: "deterministic", model: "template" }, false, reason, Date.now() - started);
    return { source: "synthesis", provider: "deterministic", text: fallback() };
  }
}
